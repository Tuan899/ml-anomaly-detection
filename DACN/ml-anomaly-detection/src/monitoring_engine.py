"""Persistent, train-once monitoring with four auditable anomaly votes.

The SQLite artifact is generated by this process, never accepted as an uploaded
pickle. Keep the database in a trusted local directory. Observations and DBA
feedback are separate: feedback never silently becomes a training/evaluation
label, and scoring never modifies a fitted model or its scaler.
"""
from __future__ import annotations

from datetime import datetime, timezone
import json
import math
from pathlib import Path
import pickle
import sqlite3
from threading import RLock

import numpy as np
import pandas as pd
from sklearn.metrics import confusion_matrix
from sklearn.preprocessing import StandardScaler

from .data_prep import robust_location_scale, robust_z_values
from .dbms_monitoring import MYSQL_METRICS, _fit_baselines
from .models import MODEL_NAMES, _make_estimator, _validate_contamination, evaluate_predictions


MIN_BASELINE_ROWS = 30
MAX_BASELINE_ROWS = 10000
MAX_INGEST_ROWS = 5000
FEEDBACK_VERDICTS = {"true_incident", "false_alarm", "unreviewed"}


def _utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def vote_level(votes: int) -> str:
    """A demonstration policy, not an estimated probability of an incident."""
    if isinstance(votes, bool) or not isinstance(votes, (int, np.integer)) or not 0 <= votes <= 4:
        raise ValueError("Vote count must be an integer from zero through four")
    return ("normal", "watch", "warning", "critical", "critical")[votes]


def _name(value, field: str, *, optional: bool = False) -> str | None:
    if optional and value is None:
        return None
    if not isinstance(value, str) or not value.strip() or len(value) > 160 or any(ord(c) < 32 for c in value):
        raise ValueError(f"{field} must be non-empty text of at most 160 characters")
    return value.strip()


def _frame(records) -> pd.DataFrame:
    if isinstance(records, pd.DataFrame):
        if records.columns.duplicated().any():
            raise ValueError("Metric column names must be unique")
        return records.copy(deep=True)
    if not isinstance(records, (list, tuple)) or not records or any(not isinstance(row, dict) for row in records):
        raise ValueError("Provide a non-empty list of metric records")
    return pd.DataFrame.from_records(records)


def _validated(frame: pd.DataFrame, *, maximum: int) -> pd.DataFrame:
    if frame.empty or len(frame) > maximum:
        raise ValueError(f"Provide between 1 and {maximum} metric records")
    required = ["timestamp", *MYSQL_METRICS]
    missing = [column for column in required if column not in frame]
    if missing:
        raise ValueError("Missing metric columns: " + ", ".join(missing))
    raw_time = frame["timestamp"]
    if raw_time.isna().any() or raw_time.map(lambda x: isinstance(x, (bool, np.bool_, int, float, np.number))).any():
        raise ValueError("Timestamps must be explicit datetime values or strings")
    timestamps = pd.to_datetime(raw_time, errors="coerce", utc=True, format="mixed")
    if timestamps.isna().any() or timestamps.duplicated().any():
        raise ValueError("Timestamps must be valid and unique within a batch")
    result = pd.DataFrame({"timestamp": timestamps})
    for metric in MYSQL_METRICS:
        raw = frame[metric]
        if raw.map(lambda value: isinstance(value, (bool, np.bool_, complex, np.complexfloating))).any():
            raise ValueError(f"{metric} must contain finite, nonnegative real measurements")
        try:
            numbers = pd.to_numeric(raw, errors="coerce")
            values = numbers.to_numpy(dtype=float, na_value=np.nan)
        except (TypeError, ValueError, OverflowError) as exc:
            raise ValueError(f"{metric} must contain finite, nonnegative real measurements") from exc
        if not np.isfinite(values).all() or (values < 0).any():
            raise ValueError(f"{metric} must contain finite, nonnegative real measurements")
        result[metric] = values
    labels = []
    for value in frame.get("label", pd.Series([None] * len(frame), index=frame.index)):
        if value is None or (isinstance(value, (float, np.floating)) and np.isnan(value)):
            labels.append(None)
        elif isinstance(value, (bool, np.bool_, complex, np.complexfloating)):
            raise ValueError("Labels must be 1 (normal), -1 (anomaly), or omitted")
        else:
            try:
                number = float(value)
            except (TypeError, ValueError) as exc:
                raise ValueError("Labels must be 1 (normal), -1 (anomaly), or omitted") from exc
            if not math.isfinite(number) or number not in (-1, 1):
                raise ValueError("Labels must be 1 (normal), -1 (anomaly), or omitted")
            labels.append(int(number))
    result["label"] = pd.Series(labels, index=result.index, dtype=object)
    scenarios = []
    for value in frame.get("scenario", pd.Series([None] * len(frame), index=frame.index)):
        if value is None or (isinstance(value, float) and np.isnan(value)):
            scenarios.append(None)
        else:
            scenarios.append(_name(value, "scenario"))
    result["scenario"] = scenarios
    event_ids = []
    for value in frame.get("event_id", pd.Series([None] * len(frame), index=frame.index)):
        if value is None or (isinstance(value, float) and np.isnan(value)):
            event_ids.append(None)
        else:
            event_ids.append(_name(value, "event_id"))
    nonempty_ids = [value for value in event_ids if value is not None]
    if len(nonempty_ids) != len(set(nonempty_ids)):
        raise ValueError("event_id values must be unique within a batch")
    result["event_id"] = event_ids
    return result.sort_values("timestamp", kind="stable").reset_index(drop=True)


class MonitoringEngine:
    """A serialized local model reference and append-only observation history."""

    def __init__(self, db_path: str | Path):
        self.db_path = str(db_path)
        if self.db_path != ":memory:":
            Path(self.db_path).expanduser().resolve().parent.mkdir(parents=True, exist_ok=True)
        self._lock = RLock()
        self._connection = sqlite3.connect(self.db_path, timeout=30, check_same_thread=False)
        self._connection.row_factory = sqlite3.Row
        self._connection.execute("PRAGMA journal_mode=WAL")
        self._connection.execute("PRAGMA foreign_keys=ON")
        self._connection.executescript("""
            CREATE TABLE IF NOT EXISTS engine_baselines (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                metadata TEXT NOT NULL,
                artifact BLOB NOT NULL
            );
            CREATE TABLE IF NOT EXISTS engine_samples (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                baseline_id INTEGER NOT NULL REFERENCES engine_baselines(id),
                source TEXT NOT NULL,
                session_id TEXT,
                timestamp TEXT NOT NULL,
                received_at TEXT NOT NULL,
                label INTEGER CHECK (label IN (-1, 1)),
                votes INTEGER NOT NULL,
                record TEXT NOT NULL,
                feedback_verdict TEXT NOT NULL DEFAULT 'unreviewed',
                feedback_note TEXT NOT NULL DEFAULT '',
                event_id TEXT
            );
            CREATE INDEX IF NOT EXISTS engine_samples_reference ON engine_samples(baseline_id, id);
            CREATE INDEX IF NOT EXISTS engine_samples_source ON engine_samples(source, id);
            CREATE TABLE IF NOT EXISTS engine_feedback_events (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                sample_id INTEGER NOT NULL REFERENCES engine_samples(id),
                changed_at TEXT NOT NULL,
                previous_verdict TEXT NOT NULL,
                verdict TEXT NOT NULL,
                note TEXT NOT NULL
            );
        """)
        columns = {row["name"] for row in self._connection.execute("PRAGMA table_info(engine_samples)")}
        if "event_id" not in columns:
            self._connection.execute("ALTER TABLE engine_samples ADD COLUMN event_id TEXT")
        self._connection.execute("""CREATE UNIQUE INDEX IF NOT EXISTS engine_samples_event
            ON engine_samples(source, IFNULL(session_id,''), event_id) WHERE event_id IS NOT NULL""")
        self._connection.commit()
        self._cached_baseline_id = None
        self._cached_bundle = None

    def close(self) -> None:
        with self._lock:
            self._connection.close()

    def _active(self) -> tuple[dict | None, dict | None]:
        row = self._connection.execute("SELECT id, metadata, artifact FROM engine_baselines ORDER BY id DESC LIMIT 1").fetchone()
        if row is None:
            return None, None
        if self._cached_baseline_id != row["id"]:
            # Only internally generated artifacts are stored; no endpoint accepts
            # uploaded pickle bytes or an arbitrary artifact path.
            self._cached_bundle = pickle.loads(row["artifact"])
            self._cached_baseline_id = row["id"]
        return json.loads(row["metadata"]), self._cached_bundle

    def baseline(self) -> dict | None:
        with self._lock:
            metadata, _ = self._active()
            return metadata

    def catalog(self) -> dict:
        """List all baseline/source scopes without loading fitted model artifacts.

        A bounded chart/history window must not determine which historical
        reference or source remains available for evidence selection.
        """
        with self._lock, self._connection:
            self._connection.execute("BEGIN")
            rows = self._connection.execute("""SELECT b.metadata, COALESCE(s.sample_count,0) AS sample_count
                FROM engine_baselines AS b
                LEFT JOIN (SELECT baseline_id,COUNT(*) AS sample_count
                           FROM engine_samples GROUP BY baseline_id) AS s ON s.baseline_id=b.id
                ORDER BY b.id DESC""").fetchall()
            baselines = [{**json.loads(row["metadata"]), "sample_count": int(row["sample_count"])} for row in rows]
            sources = [{"baseline_id": int(row["baseline_id"]), "source": row["source"],
                        "sample_count": int(row["sample_count"])}
                       for row in self._connection.execute("""SELECT baseline_id,source,COUNT(*) AS sample_count
                           FROM engine_samples GROUP BY baseline_id,source
                           ORDER BY baseline_id DESC,source ASC""").fetchall()]
            return {"baselines": baselines, "sources": sources}

    def train_baseline(self, records, *, contamination=.01, deviation_threshold=3.5,
                       source="K1", start_index=0, end_index=None) -> dict:
        """Fit only the explicitly selected normal interval and atomically activate it."""
        _validate_contamination(contamination)
        if (isinstance(deviation_threshold, bool) or not isinstance(deviation_threshold, (int, float))
                or not math.isfinite(deviation_threshold) or not 1 <= deviation_threshold <= 10):
            raise ValueError("deviation_threshold must be finite and between 1 and 10")
        source = _name(source, "source")
        original = _frame(records)
        if end_index is None:
            end_index = len(original)
        if (isinstance(start_index, bool) or not isinstance(start_index, int)
                or isinstance(end_index, bool) or not isinstance(end_index, int)
                or not 0 <= start_index < end_index <= len(original)):
            raise ValueError("Select a valid baseline interval [start_index, end_index)")
        # Unselected rows and labels cannot influence validation statistics or fit.
        train = _validated(original.iloc[start_index:end_index].reset_index(drop=True), maximum=MAX_BASELINE_ROWS)
        if len(train) < MIN_BASELINE_ROWS:
            raise ValueError(f"Need at least {MIN_BASELINE_ROWS} normal baseline records")
        if train["label"].eq(-1).any():
            raise ValueError("The selected baseline contains labeled anomalies; select a normal interval")
        values = train[list(MYSQL_METRICS)].to_numpy(dtype=float)
        scaler = StandardScaler()
        scaled = scaler.fit_transform(values)
        if not np.isfinite(scaled).all():
            raise ValueError("Feature scaling overflowed; reduce measurement magnitudes")
        center, scale = robust_location_scale(scaled)
        estimators = {}
        for name in MODEL_NAMES:
            if name != "mad":
                estimator = _make_estimator(name, float(contamination), 42, len(train), {})
                estimator.fit(scaled)
                estimators[name] = estimator
        baselines = _fit_baselines(train, float(deviation_threshold))
        metadata = {
            "id": None, "trained_at": _utc_now(), "rows": len(train), "source": source,
            "start": train["timestamp"].iloc[0].isoformat(), "end": train["timestamp"].iloc[-1].isoformat(),
            "source_start": train["timestamp"].iloc[0].isoformat(), "source_end": train["timestamp"].iloc[-1].isoformat(),
            "start_index": start_index, "end_index": end_index, "features": list(MYSQL_METRICS),
            "contamination": float(contamination), "deviation_threshold": float(deviation_threshold),
            "baselines": baselines, "scaler": {"mean": scaler.mean_.tolist(), "scale": scaler.scale_.tolist(), "fit_rows": len(train)},
            "model_names": list(MODEL_NAMES), "mad_threshold": 3.5,
            "parameters": {name: estimator.get_params(deep=False) for name, estimator in estimators.items()},
            "protocol": "Fit selected normal baseline only; freeze scaler, MAD, estimators and tolerance thresholds for later observations.",
            "vote_policy": "0 normal; 1 watch; 2 warning; 3 or 4 critical. Demonstration policy, not a calibrated probability.",
        }
        bundle = {"scaler": scaler, "mad_center": center, "mad_scale": scale,
                  "estimators": estimators, "baselines": baselines}
        artifact = pickle.dumps(bundle, protocol=pickle.HIGHEST_PROTOCOL)
        with self._lock, self._connection:
            cursor = self._connection.execute("INSERT INTO engine_baselines(metadata,artifact) VALUES (?,?)",
                                              (json.dumps(metadata, allow_nan=False), artifact))
            metadata["id"] = int(cursor.lastrowid)
            self._connection.execute("UPDATE engine_baselines SET metadata=? WHERE id=?",
                                     (json.dumps(metadata, allow_nan=False), metadata["id"]))
            self._cached_baseline_id = metadata["id"]
            self._cached_bundle = bundle
        return json.loads(json.dumps(metadata))

    def ingest(self, records, *, source="live", session_id=None) -> list[dict]:
        source = _name(source, "source")
        session_id = _name(session_id, "session_id", optional=True)
        frame = _validated(_frame(records), maximum=MAX_INGEST_ROWS)
        with self._lock, self._connection:
            # Serialize deduplication and insertion across independent engine
            # instances/processes sharing the same database, not just threads.
            self._connection.execute("BEGIN IMMEDIATE")
            existing = {}
            positions = []
            for index, row in frame.iterrows():
                old = None
                if row["event_id"] is not None:
                    old = self._connection.execute("""SELECT * FROM engine_samples
                        WHERE source=? AND IFNULL(session_id,'')=? AND event_id=?""",
                        (source, session_id or "", row["event_id"])).fetchone()
                if old is None:
                    positions.append(index)
                    continue
                record = self._record(old)
                identity = {"timestamp": row["timestamp"].isoformat(),
                            **{metric: float(row[metric]) for metric in MYSQL_METRICS},
                            "label": None if row["label"] is None else int(row["label"]),
                            "scenario": row["scenario"]}
                if any(record.get(key) != value for key, value in identity.items()):
                    raise ValueError("event_id already exists with different measurements or reference labels")
                existing[index] = record
            total_rows = len(frame)
            if not positions:
                return [existing[index] for index in range(total_rows)]
            frame = frame.iloc[positions].reset_index(drop=True)
            baseline, bundle = self._active()
            if baseline is None:
                raise ValueError("Train a normal baseline before ingesting observations")
            if (frame["timestamp"] <= pd.Timestamp(baseline["end"])).any():
                raise ValueError("Scored observations must occur after the baseline interval")
            values = frame[list(MYSQL_METRICS)].to_numpy(dtype=float)
            scaled = bundle["scaler"].transform(values)
            if not np.isfinite(scaled).all():
                raise ValueError("Feature scaling overflowed; reduce measurement magnitudes")
            scores = {"mad": 3.5 - np.abs(robust_z_values(scaled, bundle["mad_center"], bundle["mad_scale"])).max(axis=1)}
            predictions = {"mad": np.where(scores["mad"] <= 0, -1, 1)}
            for name, estimator in bundle["estimators"].items():
                predictions[name] = estimator.predict(scaled).astype(int)
                scores[name] = np.asarray(estimator.decision_function(scaled), dtype=float)
            if not all(np.isfinite(score).all() for score in scores.values()):
                raise ValueError("A model produced non-finite scores")
            received_at = _utc_now()
            output = []
            for index, row in frame.iterrows():
                evidence = []
                for metric in MYSQL_METRICS:
                    reference = bundle["baselines"][metric]
                    actual = float(row[metric])
                    median = reference["median"]
                    delta = actual - median
                    relative = delta / abs(median) if median != 0 else None
                    if relative is not None and not math.isfinite(relative):
                        relative = None
                    evidence.append({"metric": metric, "actual": actual, "baseline": median,
                                     "delta": delta, "relative_change": relative,
                                     "allowed_deviation": reference["allowed_deviation"],
                                     "material": bool(abs(delta) > reference["allowed_deviation"])})
                material = any(item["material"] for item in evidence)
                raw = {name: int(predictions[name][index]) for name in MODEL_NAMES}
                guarded = {name: (-1 if raw[name] == -1 and material else 1) for name in MODEL_NAMES}
                raw_voters = [name for name in MODEL_NAMES if raw[name] == -1]
                voters = [name for name in MODEL_NAMES if guarded[name] == -1]
                label = row["label"]
                output.append({"timestamp": row["timestamp"].isoformat(), "received_at": received_at,
                    **{metric: float(row[metric]) for metric in MYSQL_METRICS},
                    "source": source, "session_id": session_id, "baseline_id": baseline["id"],
                    "scenario": row["scenario"], "event_id": row["event_id"],
                    "label": None if label is None else int(label),
                    "raw_predictions": raw, "predictions": guarded,
                    "scores": {name: float(scores[name][index]) for name in MODEL_NAMES},
                    "raw_votes": len(raw_voters), "votes": len(voters),
                    "raw_level": vote_level(len(raw_voters)), "level": vote_level(len(voters)),
                    "raw_voters": raw_voters, "voters": voters, "evidence": evidence,
                    "feedback": {"verdict": "unreviewed", "note": ""}})
            # Score the entire batch successfully before committing any observation.
            with self._connection:
                for record in output:
                    cursor = self._connection.execute("""INSERT INTO engine_samples
                        (baseline_id,source,session_id,timestamp,received_at,label,votes,record,event_id)
                        VALUES (?,?,?,?,?,?,?,?,?)""", (record["baseline_id"], source, session_id,
                        record["timestamp"], received_at, record["label"], record["votes"],
                        json.dumps(record, allow_nan=False), record["event_id"]))
                    record["id"] = int(cursor.lastrowid)
            fresh = dict(zip(positions, output))
            return [existing[index] if index in existing else fresh[index] for index in range(total_rows)]

    @staticmethod
    def _record(row) -> dict:
        value = json.loads(row["record"])
        value["id"] = row["id"]
        value["feedback"] = {"verdict": row["feedback_verdict"], "note": row["feedback_note"]}
        return value

    def _where(self, *, source=None, baseline_id=None, after_id=0) -> tuple[list[str], list]:
        clauses, params = [], []
        if source is not None:
            clauses.append("source=?")
            params.append(_name(source, "source"))
        if baseline_id is not None:
            if isinstance(baseline_id, bool) or not isinstance(baseline_id, int) or baseline_id < 1:
                raise ValueError("baseline_id must be a positive integer")
            clauses.append("baseline_id=?")
            params.append(baseline_id)
        if isinstance(after_id, bool) or not isinstance(after_id, int) or after_id < 0:
            raise ValueError("after_id must be a nonnegative integer")
        if after_id:
            clauses.append("id>?")
            params.append(after_id)
        return clauses, params

    @staticmethod
    def _limit(limit):
        if isinstance(limit, bool) or not isinstance(limit, int) or not 1 <= limit <= 10000:
            raise ValueError("limit must be an integer between 1 and 10000")
        return limit

    def history(self, *, limit=300, after_id=0, source=None, baseline_id=None) -> list[dict]:
        clauses, params = self._where(source=source, baseline_id=baseline_id, after_id=after_id)
        where = " WHERE " + " AND ".join(clauses) if clauses else ""
        with self._lock:
            rows = self._connection.execute("SELECT * FROM engine_samples" + where + " ORDER BY id DESC LIMIT ?",
                                             [*params, self._limit(limit)]).fetchall()
            return [self._record(row) for row in reversed(rows)]

    def get_sample(self, sample_id: int) -> dict:
        """Read one exact observation, including historical baseline versions."""
        if type(sample_id) is not int or not 1 <= sample_id <= 9223372036854775807:
            raise ValueError("sample_id must be a positive SQLite integer")
        with self._lock:
            row = self._connection.execute("SELECT * FROM engine_samples WHERE id=?", (sample_id,)).fetchone()
            if row is None:
                raise KeyError("Observation not found")
            return self._record(row)

    def alerts(self, *, limit=100, source=None, baseline_id=None) -> list[dict]:
        clauses, params = self._where(source=source, baseline_id=baseline_id)
        clauses.append("votes>0")
        with self._lock:
            rows = self._connection.execute("SELECT * FROM engine_samples WHERE " + " AND ".join(clauses)
                                             + " ORDER BY id DESC LIMIT ?", [*params, self._limit(limit)]).fetchall()
            return [self._record(row) for row in rows]

    def feedback(self, sample_id, verdict, note="") -> dict:
        if isinstance(sample_id, bool) or not isinstance(sample_id, int) or sample_id < 1:
            raise ValueError("sample_id must be a positive integer")
        if not isinstance(verdict, str) or verdict not in FEEDBACK_VERDICTS:
            raise ValueError("verdict must be true_incident, false_alarm, or unreviewed")
        if not isinstance(note, str) or len(note) > 2000:
            raise ValueError("Feedback note must be text of at most 2000 characters")
        with self._lock, self._connection:
            self._connection.execute("BEGIN IMMEDIATE")
            previous = self._connection.execute("SELECT * FROM engine_samples WHERE id=?", (sample_id,)).fetchone()
            if previous is None:
                raise ValueError("Observation not found")
            self._connection.execute("INSERT INTO engine_feedback_events(sample_id,changed_at,previous_verdict,verdict,note) VALUES (?,?,?,?,?)",
                                     (sample_id, _utc_now(), previous["feedback_verdict"], verdict, note))
            self._connection.execute("UPDATE engine_samples SET feedback_verdict=?,feedback_note=? WHERE id=?", (verdict, note, sample_id))
            row = self._connection.execute("SELECT * FROM engine_samples WHERE id=?", (sample_id,)).fetchone()
            return self._record(row)

    def evaluation(self, *, source=None, baseline_id=None) -> dict:
        """Use reference labels only, scoped to one baseline version by default."""
        with self._lock:
            if baseline_id is None:
                baseline = self.baseline()
                baseline_id = baseline["id"] if baseline else None
            clauses, params = self._where(source=source, baseline_id=baseline_id)
            where = " WHERE " + " AND ".join(clauses) if clauses else ""
            rows = self._connection.execute("SELECT * FROM engine_samples" + where + " ORDER BY id", params).fetchall()
            records = [self._record(row) for row in rows]
        return self._evaluate_records(records, source)

    @staticmethod
    def _evaluate_records(records: list[dict], source) -> dict:
        labeled = [record for record in records if record["label"] in (1, -1)]
        result = {"rows": len(records), "labeled_rows": len(labeled),
                  "normal_rows": sum(record["label"] == 1 for record in labeled),
                  "anomaly_rows": sum(record["label"] == -1 for record in labeled),
                  "baseline_ids": sorted({record["baseline_id"] for record in records}),
                  "source": source, "raw": {}, "guarded": {},
                  "confusion_matrix_order": {"rows": ["normal", "anomaly"], "columns": ["normal", "anomaly"]}}
        if not labeled:
            return result
        truth = np.array([record["label"] for record in labeled], dtype=int)
        for scope, field in (("raw", "raw_predictions"), ("guarded", "predictions")):
            for name in MODEL_NAMES:
                predicted = np.array([record[field][name] for record in labeled], dtype=int)
                matrix = confusion_matrix(truth, predicted, labels=[1, -1]).astype(int).tolist()
                result[scope][name] = {**evaluate_predictions(truth, predicted),
                    "tn": matrix[0][0], "fp": matrix[0][1], "fn": matrix[1][0], "tp": matrix[1][1],
                    "confusion_matrix": matrix}
        return result

    def evidence(self, *, source=None, baseline_id=None) -> dict:
        """Export all selected observations and matching metrics from one snapshot.

        Screen history is deliberately bounded; an evidence export is not. A
        SQLite read transaction also keeps this consistent if a second service
        instance ingests or activates another baseline during the export.
        """
        if source is not None:
            source = _name(source, "source")
        if baseline_id is not None:
            # Share the same strict identifier validation as history/evaluation.
            self._where(baseline_id=baseline_id)
        with self._lock, self._connection:
            self._connection.execute("BEGIN")
            if baseline_id is None:
                reference = self._connection.execute("SELECT id,metadata FROM engine_baselines ORDER BY id DESC LIMIT 1").fetchone()
            else:
                reference = self._connection.execute("SELECT id,metadata FROM engine_baselines WHERE id=?", (baseline_id,)).fetchone()
                if reference is None:
                    raise ValueError("Selected baseline not found")
            baseline = json.loads(reference["metadata"]) if reference is not None else None
            selected_id = reference["id"] if reference is not None else None
            clauses, params = self._where(source=source, baseline_id=selected_id)
            where = " WHERE " + " AND ".join(clauses) if clauses else ""
            rows = self._connection.execute("SELECT * FROM engine_samples" + where + " ORDER BY id", params).fetchall()
            records = [self._record(row) for row in rows]
            return {"baseline": baseline, "evaluation": self._evaluate_records(records, source),
                    "samples": records, "exported_at": _utc_now()}
